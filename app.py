"""NetSentry website: receive traffic values and display a model prediction.

The machine-learning work is in data_pipeline.py and train_model.py.
This file only handles web requests and checks the user's form inputs.
"""

import json
import math
import secrets
from functools import lru_cache
from pathlib import Path

from flask import Flask, jsonify, render_template, request
from sklearn.model_selection import train_test_split

from data_pipeline import load_dataset
from model_service import DATASET_NAME, FEATURE_NAMES, load_model, predict


app = Flask(__name__)
PROJECT_DIR = Path(__file__).resolve().parent
MODEL_PATH = PROJECT_DIR / "model" / "firewall_random_forest.joblib"
REPORT_PATH = PROJECT_DIR / "data" / "evaluation_report.json"
DATASET_PATH = PROJECT_DIR / "data" / "log2.csv"

# Name, label, hint and example value for the 11 network traffic inputs.
FORM_FIELDS = [
    ("source_port", "Source port", "Sender connection port.", 51426),
    ("destination_port", "Destination port", "Receiving service port.", 443),
    ("nat_source_port", "NAT source port", "Translated sender port.", 3125),
    ("nat_destination_port", "NAT destination port", "Translated destination port.", 443),
    ("total_bytes", "Total bytes", "Total transferred data in bytes.", 15947),
    ("bytes_sent", "Bytes sent", "Bytes sent in the forward direction.", 5526),
    ("bytes_received", "Bytes received", "Bytes received in the return direction.", 10421),
    ("total_packets", "Total packets", "Total packets in the connection.", 38),
    ("connection_duration", "Elapsed time", "Connection duration in seconds.", 622),
    ("forward_packets", "Packets sent", "Forward-direction packet count.", 16),
    ("backward_packets", "Packets received", "Return-direction packet count.", 22),
]

# These fields must contain whole numbers. Duration may be a decimal.
WHOLE_NUMBER_FIELDS = set(FEATURE_NAMES) - {"connection_duration"}
PORT_FIELDS = ("source_port", "destination_port",
               "nat_source_port", "nat_destination_port")

MODEL_LOAD_ERROR = (
    "The trained model could not be loaded. Run train_model.bat to retrain it, "
    "then restart NetSentry."
)

ACTION_DETAILS = {
    "Allow": {
        "description": "The model predicts this record resembles firewall traffic labeled Allow in the training data.",
        "explanation": "This is a prediction from historical records, not a live firewall rule or a security guarantee.",
    },
    "Deny": {
        "description": "The model predicts this record resembles firewall traffic labeled Deny in the training data.",
        "explanation": "This is a prediction from historical records, not a live firewall rule or a security guarantee.",
    },
    "Drop": {
        "description": "The model predicts this record resembles firewall traffic labeled Drop in the training data.",
        "explanation": "This is a prediction from historical records, not a live firewall rule or a security guarantee.",
    },
    "Reset": {
        "description": "The model predicts this record resembles traffic labeled Reset-Both in the training data.",
        "explanation": "Reset-Both is displayed as Reset. This prediction does not control a real connection.",
    },
}


def load_saved_model():
    """Return the trained model, or None if training has not been run yet."""
    if MODEL_PATH.exists():
        return load_model(MODEL_PATH)
    return None


def read_traffic(payload):
    """Turn the submitted form into 11 validated numbers, in feature order."""
    values = {}

    for field in FEATURE_NAMES:
        number = payload[field]
        label = field.replace("_", " ").title()

        if isinstance(number, bool):
            raise ValueError(f"{label} must be a valid number.")

        number = float(number)
        if not math.isfinite(number):
            raise ValueError(f"{label} must be a valid number.")
        if number < 0:
            raise ValueError("Traffic values cannot be negative.")
        if field in WHOLE_NUMBER_FIELDS and not number.is_integer():
            raise ValueError(f"{label} must be a whole number.")

        values[field] = number

    # Ports are always between 0 and 65,535.
    for field in PORT_FIELDS:
        if values[field] > 65535:
            raise ValueError("Ports must be between 0 and 65535.")

    if values["total_packets"] < 1:
        raise ValueError("Total packets must be at least 1.")

    sent_packets = values["forward_packets"] + values["backward_packets"]
    if sent_packets > values["total_packets"]:
        raise ValueError("Forward plus backward packet counts cannot exceed total packets.")

    transferred_bytes = values["bytes_sent"] + values["bytes_received"]
    if transferred_bytes > values["total_bytes"] * 1.02:
        raise ValueError("Bytes Sent plus Bytes Received should not exceed Total Bytes. Check your values.")

    return [values[field] for field in FEATURE_NAMES]


def training_results():
    """Read the results generated by train_model.py, if available."""
    try:
        report = json.loads(REPORT_PATH.read_text(encoding="utf-8"))
        cv = report["cross_validation"]
        if not cv:
            return None

        return {
            "dataset": report["dataset"],
            "test_accuracy": f"{report['accuracy'] * 100:.2f}%",
            "macro_f1": f"{report['macro_f1']:.4f}",
            "cv_accuracy": f"{cv['mean_accuracy'] * 100:.2f}%",
            "train_accuracy": f"{cv['mean_training_accuracy'] * 100:.3f}%",
            "gap": f"{cv['training_validation_gap_percentage_points']:.2f} pp",
            "train_count": f"{report['train_split_size']:,}",
            "test_count": f"{report['test_split_size']:,}",
            "folds": cv["folds"],
        }
    except (OSError, KeyError, TypeError, ValueError):
        app.logger.warning("Training results are missing or unreadable")
        return None


@app.get("/")
def index():
    return render_template(
        "index.html", form_fields=FORM_FIELDS, results=training_results()
    )


@app.get("/api/health")
def health():
    try:
        model = load_saved_model()
    except Exception:
        app.logger.exception("Failed to load the NetSentry model during health check")
        return jsonify({
            "status": "model_error",
            "model_ready": False,
            "error": MODEL_LOAD_ERROR,
        }), 503

    return jsonify({
        "status": "ready" if model is not None else "model_missing",
        "model_ready": model is not None,
        "dataset": model.get("dataset_name", DATASET_NAME) if model else DATASET_NAME,
    })


@lru_cache(maxsize=1)
def _sample_rows():
    """Recreate the training script's 20% held-out test split for Generate.

    Apply the exact same cleaned-row ordering, stratification and split seed as
    train_model.py. Never sample from the 80% training partition.
    """
    records, _, _ = load_dataset(DATASET_PATH)
    _, test_rows = train_test_split(
        records, test_size=0.2, random_state=42,
        stratify=[row["action"] for row in records],
    )
    complete = tuple(
        tuple(record["features"]) for record in test_rows
        if all(math.isfinite(value) for value in record["features"])
    )
    if not complete:
        raise ValueError("No complete held-out test records are available.")
    return complete


@app.get("/api/sample")
def sample_route():
    """Return one held-out test row without its target action label."""
    try:
        features = secrets.choice(_sample_rows())
    except (OSError, ValueError):
        app.logger.exception("Could not load a sample from the firewall dataset")
        return jsonify({"error": "Dataset examples are unavailable. Check data/log2.csv."}), 503
    return jsonify({
        "features": dict(zip(FEATURE_NAMES, features)),
        "source": "log2.csv",
        "split": "test",
    })


@app.post("/api/predict")
def predict_route():
    try:
        model = load_saved_model()
    except Exception:
        app.logger.exception("Failed to load the NetSentry model for prediction")
        return jsonify({"error": MODEL_LOAD_ERROR}), 503

    if model is None:
        return jsonify({
            "error": "The real-dataset model has not been trained yet. "
                     "Provide data/log2.csv and run: python train_model.py"
        }), 503

    payload = request.get_json(silent=True)
    if not isinstance(payload, dict):
        return jsonify({"error": "Could not read the submitted form. Please try again."}), 400

    try:
        traffic = read_traffic(payload)
        action, confidence, _probabilities = predict(model, traffic)
    except KeyError as error:
        return jsonify({"error": f"Missing required input: {error.args[0]}"}), 400
    except (TypeError, ValueError, OverflowError) as error:
        return jsonify({"error": str(error) or "Please check your inputs."}), 400

    details = ACTION_DETAILS.get(action, ACTION_DETAILS["Allow"])
    return jsonify({
        "action": action,
        "confidence": confidence,
        "description": details["description"],
        "explanation": details["explanation"],
        "model_type": "scikit-learn RandomForestClassifier",
        "dataset": model.get("dataset_name", DATASET_NAME),
        "is_synthetic_demo_model": False,
    })


if __name__ == "__main__":
    # Keep the local website accessible only from this computer.
    app.run(host="127.0.0.1", port=5000, debug=False)
